create or replace function public.admin_get_dashboard()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_result jsonb;
begin
  perform public.assert_admin();

  select jsonb_build_object(
    'state', jsonb_build_object(
      'registration_open', s.registration_open,
      'draw_status', s.draw_status,
      'draw_done', s.draw_status = 'drawn',
      'draw_round', s.draw_round,
      'drawn_at', s.drawn_at,
      'updated_at', s.updated_at
    ),
    'stats', jsonb_build_object(
      'total', (select count(*)::int from public.participants),
      'assigned', (select count(*)::int from public.assignments),
      'pending', (
        select count(*)::int
        from public.participants p
        where not exists (
          select 1 from public.assignments a where a.giver_id = p.id
        )
      )
    ),
    'participants', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', p.id,
          'first_name', p.first_name,
          'last_name', p.last_name,
          'shoe_size', p.shoe_size,
          'created_at', p.created_at,
          'receiver', case
            when a.id is not null then jsonb_build_object(
              'first_name', r.first_name,
              'last_name', r.last_name,
              'shoe_size', r.shoe_size
            )
            else null
          end
        )
        order by lower(p.last_name), lower(p.first_name), p.created_at
      )
      from public.participants p
      left join public.assignments a on a.giver_id = p.id
      left join public.participants r on r.id = a.receiver_id
    ), '[]'::jsonb)
  )
  into v_result
  from public.exchange_state s
  where s.singleton = true;

  return v_result;
end;
$$;

create or replace function public.admin_start_full_draw()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_ids uuid[];
  v_givers uuid[];
  v_receivers uuid[];
  v_n integer;
  v_round integer;
  v_attempt integer := 0;
  v_ok boolean;
  i integer;
begin
  perform public.assert_admin();
  perform pg_advisory_xact_lock(74201926);

  select array_agg(id) into v_ids
  from public.participants;

  v_n := coalesce(array_length(v_ids, 1), 0);

  if v_n < 2 then
    raise exception 'Se necesitan al menos 2 participantes registrados para realizar el sorteo.'
      using errcode = 'P0001';
  end if;

  select coalesce(draw_round, 0) + 1 into v_round
  from public.exchange_state
  where singleton = true;

  -- Se intenta una permutación aleatoria sin auto-regalos.
  -- Con 40 personas la probabilidad de fallar 200 veces es
  -- prácticamente cero; aun así hay un plan B determinista.
  loop
    v_attempt := v_attempt + 1;

    select array_agg(t.id order by random()) into v_givers
    from unnest(v_ids) as t(id);

    select array_agg(t.id order by random()) into v_receivers
    from unnest(v_ids) as t(id);

    v_ok := true;

    for i in 1..v_n loop
      if v_givers[i] = v_receivers[i] then
        v_ok := false;
        exit;
      end if;
    end loop;

    exit when v_ok or v_attempt >= 200;
  end loop;

  -- Plan B: rotar los receptores garantiza que nadie se regale a sí mismo.
  if not v_ok then
    v_receivers := array_append(v_givers[2:v_n], v_givers[1]);
  end if;

  -- Supabase puede tener activa la extensión "safeupdate", que rechaza
  -- DELETE sin WHERE incluso dentro de funciones. El WHERE es obligatorio
  -- aquí para que el sorteo funcione en producción.
  delete from public.assignments where id is not null;

  for i in 1..v_n loop
    insert into public.assignments (giver_id, receiver_id, draw_round)
    values (v_givers[i], v_receivers[i], v_round);
  end loop;

  update public.exchange_state
  set draw_status = 'drawn',
      draw_round = v_round,
      drawn_at = now(),
      updated_at = now()
  where singleton = true;

  return jsonb_build_object(
    'ok', true,
    'mode', 'full',
    'round', v_round,
    'total', v_n,
    'assigned', v_n,
    'modified', v_n
  );
end;
$$;

create or replace function public.admin_integrate_new_participants()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_new uuid[];
  v_n integer;
  v_existing_count integer;
  v_edge public.assignments%rowtype;
  v_round integer;
  v_total integer;
  i integer;
begin
  perform public.assert_admin();
  perform pg_advisory_xact_lock(74201926);

  select array_agg(p.id order by random()) into v_new
  from public.participants p
  where not exists (
    select 1 from public.assignments a where a.giver_id = p.id
  );

  v_n := coalesce(array_length(v_new, 1), 0);

  select count(*) into v_existing_count
  from public.assignments;

  select coalesce(draw_round, 0) + 1 into v_round
  from public.exchange_state
  where singleton = true;

  if v_n = 0 then
    return jsonb_build_object(
      'ok', true,
      'mode', 'none',
      'round', greatest(v_round - 1, 0),
      'integrated', 0,
      'message', 'Todos los participantes ya tienen una asignación.'
    );
  end if;

  -- Si todavía no existe ningún sorteo, hacemos el sorteo completo.
  if v_existing_count = 0 then
    return public.admin_start_full_draw();
  end if;

  -- Se corta una sola asignación existente y se inserta una cadena:
  -- A -> nuevo1 -> nuevo2 -> ... -> nuevoN -> R
  -- Así se conservan todas las demás asignaciones y todos quedan incluidos.
  select * into v_edge
  from public.assignments
  order by random()
  limit 1;

  delete from public.assignments where id = v_edge.id;

  insert into public.assignments (giver_id, receiver_id, draw_round)
  values (v_edge.giver_id, v_new[1], v_round);

  for i in 1..v_n - 1 loop
    insert into public.assignments (giver_id, receiver_id, draw_round)
    values (v_new[i], v_new[i + 1], v_round);
  end loop;

  insert into public.assignments (giver_id, receiver_id, draw_round)
  values (v_new[v_n], v_edge.receiver_id, v_round);

  select count(*) into v_total
  from public.participants;

  update public.exchange_state
  set draw_status = 'drawn',
      draw_round = v_round,
      drawn_at = now(),
      updated_at = now()
  where singleton = true;

  return jsonb_build_object(
    'ok', true,
    'mode', 'integrate',
    'round', v_round,
    'integrated', v_n,
    'total', v_total,
    'assigned', v_total,
    'modified_existing', 1
  );
end;
$$;

create or replace function public.admin_set_registration_open(p_open boolean)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.assert_admin();

  update public.exchange_state
  set registration_open = p_open,
      updated_at = now()
  where singleton = true;

  return jsonb_build_object('ok', true, 'registration_open', p_open);
end;
$$;

create or replace function public.admin_delete_pending_participant(p_participant_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.assert_admin();
  perform pg_advisory_xact_lock(74201926);

  if exists (
    select 1
    from public.assignments
    where giver_id = p_participant_id
       or receiver_id = p_participant_id
  ) then
    raise exception 'No se puede eliminar a un participante que ya tiene asignación.'
      using errcode = 'P0001';
  end if;

  delete from public.participants
  where id = p_participant_id;

  if not found then
    raise exception 'El participante no existe.'
      using errcode = 'P0001';
  end if;

  return jsonb_build_object('ok', true, 'deleted_id', p_participant_id);
end;
$$;

create or replace function public.admin_reset_all()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.assert_admin();
  perform pg_advisory_xact_lock(74201926);

  -- Borrar asignaciones (con WHERE para pg-safeupdate)
  delete from public.assignments where id is not null;

  -- Borrar participantes (con WHERE para pg-safeupdate)
  delete from public.participants where id is not null;

  -- Reiniciar estado del sorteo
  update public.exchange_state
  set draw_status = 'pending',
      draw_round = 0,
      drawn_at = null,
      updated_at = now()
  where singleton = true;

  return jsonb_build_object('ok', true, 'message', 'Base de datos reiniciada: asignaciones y participantes borrados, sorteo a cero.');
end;
$$;

