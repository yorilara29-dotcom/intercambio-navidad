create or replace function public.get_public_state()
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'registration_open', s.registration_open,
    'draw_done', s.draw_status = 'drawn',
    'draw_round', s.draw_round,
    'participant_count', (select count(*)::int from public.participants),
    'assigned_count', (select count(*)::int from public.assignments),
    'server_time', now()
  )
  from public.exchange_state s
  where s.singleton = true;
$$;

create or replace function public.register_participant(
  p_first_name text,
  p_last_name text,
  p_shoe_size text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_state public.exchange_state%rowtype;
  v_participant public.participants%rowtype;
  v_first text;
  v_last text;
  v_size text;
begin
  select * into v_state
  from public.exchange_state
  where singleton = true;

  if not found then
    raise exception 'La configuración del intercambio no está inicializada.'
      using errcode = 'P0001';
  end if;

  if not v_state.registration_open then
    raise exception 'El registro está cerrado. Contacta al administrador.'
      using errcode = 'P0001';
  end if;

  v_first := regexp_replace(btrim(coalesce(p_first_name, '')), '\s+', ' ', 'g');
  v_last  := regexp_replace(btrim(coalesce(p_last_name,  '')), '\s+', ' ', 'g');
  v_size  := regexp_replace(btrim(coalesce(p_shoe_size,  '')), '\s+', ' ', 'g');

  if v_first = '' or v_last = '' then
    raise exception 'Nombre y apellido son obligatorios.'
      using errcode = 'P0001';
  end if;

  if char_length(v_first) > 60 or char_length(v_last) > 60 then
    raise exception 'El nombre o el apellido son demasiado largos.'
      using errcode = 'P0001';
  end if;

  if v_size = '' then
    raise exception 'La talla de calzado es obligatoria.'
      using errcode = 'P0001';
  end if;

  if char_length(v_size) > 20 then
    raise exception 'La talla de calzado es demasiado larga.'
      using errcode = 'P0001';
  end if;

  insert into public.participants (first_name, last_name, shoe_size)
  values (v_first, v_last, v_size)
  returning * into v_participant;

  return jsonb_build_object(
    'ok', true,
    'participant', jsonb_build_object(
      'id', v_participant.id,
      'first_name', v_participant.first_name,
      'last_name', v_participant.last_name,
      'shoe_size', v_participant.shoe_size
    ),
    'draw_done', v_state.draw_status = 'drawn'
  );
exception
  when unique_violation then
    raise exception 'Ya existe un participante con ese nombre y apellido. Si eres otra persona con el mismo nombre, agrega tu segundo apellido en el campo Apellido.'
      using errcode = 'P0001';
end;
$$;

create or replace function public.get_my_assignment(
  p_first_name text,
  p_last_name text,
  p_shoe_size text
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_state public.exchange_state%rowtype;
  v_participant public.participants%rowtype;
  v_receiver public.participants%rowtype;
  v_has_assignment boolean;
begin
  select * into v_state
  from public.exchange_state
  where singleton = true;

  select * into v_participant
  from public.participants
  where public.normalize_name(first_name) = public.normalize_name(p_first_name)
    and public.normalize_name(last_name)  = public.normalize_name(p_last_name)
    and public.normalize_shoe_size(shoe_size) = public.normalize_shoe_size(p_shoe_size)
  limit 1;

  if not found then
    return jsonb_build_object(
      'found', false,
      'draw_done', coalesce(v_state.draw_status = 'drawn', false)
    );
  end if;

  select p.* into v_receiver
  from public.assignments a
  join public.participants p on p.id = a.receiver_id
  where a.giver_id = v_participant.id;

  v_has_assignment := found;

  return jsonb_build_object(
    'found', true,
    'draw_done', coalesce(v_state.draw_status = 'drawn', false),
    'has_assignment', v_has_assignment,
    'participant', jsonb_build_object(
      'first_name', v_participant.first_name,
      'last_name', v_participant.last_name,
      'shoe_size', v_participant.shoe_size
    ),
    'receiver', case
      when v_has_assignment then jsonb_build_object(
        'first_name', v_receiver.first_name,
        'last_name', v_receiver.last_name,
        'shoe_size', v_receiver.shoe_size
      )
      else null
    end
  );
end;
$$;

