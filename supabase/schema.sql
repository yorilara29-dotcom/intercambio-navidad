create or replace function public.normalize_name(p_value text)
returns text
language sql
immutable
set search_path = pg_catalog, pg_temp
as $$
  select lower(regexp_replace(btrim(coalesce(p_value, '')), '\s+', ' ', 'g'));
$$;

create or replace function public.normalize_shoe_size(p_value text)
returns text
language sql
immutable
set search_path = pg_catalog, pg_temp
as $$
  with normalized as (
    select lower(
      regexp_replace(
        btrim(replace(coalesce(p_value, ''), ',', '.')),
        '\s+',
        ' ',
        'g'
      )
    ) as value
  )
  select case
    when value ~ '^[0-9]{1,3}\.[0-9]+$'
      then rtrim(rtrim(value, '0'), '.')
    else value
  end
  from normalized;
$$;

create or replace function public.assert_admin()
returns void
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión como administrador.'
      using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.admins a where a.user_id = auth.uid()
  ) then
    raise exception 'Esta cuenta no tiene permisos de administrador.'
      using errcode = '42501';
  end if;
end;
$$;

