-- ------------------------------------------------------------
-- 1. Tablas
-- ------------------------------------------------------------

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.participants (
  id uuid primary key default gen_random_uuid(),
  first_name text not null,
  last_name text not null,
  shoe_size text not null,
  created_at timestamptz not null default now(),
  constraint participants_first_name_ck
    check (char_length(btrim(first_name)) between 1 and 60),
  constraint participants_last_name_ck
    check (char_length(btrim(last_name)) between 1 and 60),
  constraint participants_shoe_size_ck
    check (char_length(btrim(shoe_size)) between 1 and 20)
);

-- Un mismo nombre completo no puede registrarse dos veces.
-- Si existieran dos personas homónimas, pueden agregar su segundo
-- apellido en el campo "Apellido".
create unique index if not exists participants_full_name_uidx
  on public.participants (lower(btrim(first_name)), lower(btrim(last_name)));

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  giver_id uuid not null references public.participants(id) on delete restrict,
  receiver_id uuid not null references public.participants(id) on delete restrict,
  draw_round integer not null check (draw_round > 0),
  created_at timestamptz not null default now(),
  constraint assignments_no_self_ck check (giver_id <> receiver_id),
  constraint assignments_giver_uidx unique (giver_id),
  constraint assignments_receiver_uidx unique (receiver_id)
);

create table if not exists public.exchange_state (
  singleton boolean primary key default true,
  registration_open boolean not null default true,
  draw_status text not null default 'pending',
  draw_round integer not null default 0,
  drawn_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint exchange_state_singleton_ck check (singleton),
  constraint exchange_state_status_ck
    check (draw_status in ('pending', 'drawn'))
);

insert into public.exchange_state (singleton)
values (true)
on conflict (singleton) do nothing;

